test_that("the opt-in real pilot retains its complete scoped schedule, retry, monitoring and report", {
  root <- Sys.getenv("LIDAR_CHAT11_PILOT_ROOT")
  if (!nzchar(root)) skip("Set LIDAR_CHAT11_PILOT_ROOT to review the completed real pilot.")
  f <- benchmark_fixture()
  env <- f$env
  manifest <- readRDS(file.path(root, "manifest.rds"))
  receipt <- readRDS(file.path(root, "pilot-review.rds"))
  records <- env$benchmark_read_campaign(dirname(dirname(root)), manifest$campaign_id)
  identity <- manifest$identity
  expect_equal(nrow(identity$selection), 18L)
  expect_equal(length(unique(identity$selection$task_id)), 9L)
  expect_setequal(identity$runs$cores, c(1L, 2L))
  expect_setequal(identity$config$tools, c("lidR", "lasR", "lastools"))
  expect_length(identity$environment$native, 4L)
  expect_equal(nrow(identity$schedule), 216L)
  expect_equal(nrow(records), 217L)
  expect_setequal(records$schedule_index, identity$schedule$schedule_index)
  expect_true(all(records$monitoring_status[records$execution_status != "skipped"] %in%
                    c("available", "partial")))
  expect_true(any(records$monitoring_sample_count > 0L, na.rm = TRUE))
  expect_identical(receipt$retry_after, receipt$retry_before + 1L)
  expect_identical(receipt$resume_after, receipt$resume_before)
  expect_equal(nrow(records[records$schedule_index == receipt$retry_schedule_index, ]), 2L)
  provenance <- identity$config$pilot_provenance
  expect_setequal(provenance$tiles, c("298000_5093000", "298000_5094000"))
  expect_identical(provenance$density, 1L)
  expect_equal(nrow(provenance$sources), 4L)
  expect_identical(env$benchmark_checksums(provenance$sources$path), provenance$sources)
  expect_identical(env$benchmark_checksums(provenance$staged$path), provenance$staged)
  expect_identical(identity$config$input_metadata$horizontal_epsg, 2959L)
  expect_identical(identity$config$input_metadata$vertical_epsg, 5713L)
  expect_true(identity$config$accept_known_surface_discrepancies)
  expect_true(identity$config$diagnostic_lasR)
  expect_true(file.exists(file.path(receipt$report, "_site", "index.html")))
  expect_true(file.exists(file.path(receipt$report, "_site", "results_complex.html")))
  expect_false(dir.exists(file.path(dirname(dirname(root)), ".benchmark-execution-lock")))
})
